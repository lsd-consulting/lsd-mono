// The large shared test report, generated rather than committed: about 100 KB at the default 100
// participants and 400 messages, and megabytes at the sizes a perf run wants. Plain JavaScript
// with no dependencies, so any Node 22 consumer can run it; `node generated/large.mjs > large.json`
// writes the default report to a file. The same arguments always give the same report, and it
// follows lsd-report.schema.json.
import { pathToFileURL } from 'node:url'

const TYPES = ['PARTICIPANT', 'ACTOR', 'BOUNDARY', 'DATABASE', 'QUEUE', 'ENTITY']

/**
 * A report with one scenario of `participants` lanes and `messages` messages: calls with replies,
 * asynchronous messages, a section every 100 messages, a note every 50, durations on every
 * third call and a small payload on every fifth message.
 *
 * @param {{ participants?: number, messages?: number }} [size]
 */
export function largeReport({ participants = 100, messages = 400 } = {}) {
  const lanes = Array.from({ length: participants }, (_, i) => ({
    id: `service-${i + 1}`,
    name: `Service ${i + 1}`,
    type: TYPES[i % TYPES.length],
  }))
  const events = []
  let id = 0
  const next = () => String(++id)
  let sent = 0
  while (sent < messages) {
    if (sent % 100 === 0) events.push({ kind: 'section', id: next(), title: `Messages ${sent + 1} to ${sent + 100}` })
    if (sent % 50 === 25) events.push({ kind: 'note', id: next(), text: `note after ${sent} messages`, over: lanes[0].id, placement: 'over' })
    const from = lanes[sent % participants].id
    const to = lanes[(sent * 7 + 1) % participants].id
    const message = { kind: 'message', id: next(), from, to, label: `call ${sent + 1}`, type: 'SYNCHRONOUS' }
    if (sent % 3 === 0) message.durationMs = 5 + (sent % 40)
    if (sent % 5 === 0) message.data = { method: 'POST', path: `/items/${sent}`, body: { n: sent, tags: ['a', 'b'] } }
    if (sent % 4 === 3) Object.assign(message, { type: 'ASYNCHRONOUS', label: `event ${sent + 1}` })
    events.push(message)
    sent++
    if (message.type === 'SYNCHRONOUS' && sent < messages) {
      events.push({ kind: 'message', id: next(), from: to, to: from, label: `reply ${sent}`, type: 'SYNCHRONOUS_RESPONSE' })
      sent++
    }
  }
  return {
    schemaVersion: '0.1.0',
    title: `Large: ${participants} participants, ${messages} messages`,
    generatedAt: '2026-01-01T12:00:00Z',
    generator: 'conformance/generated/large.mjs',
    status: 'success',
    options: { metricsEnabled: true, labelMaxWidth: 200, usagePing: false, source: 'api' },
    scenarios: [
      {
        id: 'large',
        title: `${participants} participants, ${messages} messages`,
        status: 'success',
        description: 'Generated by conformance/generated/large.mjs.',
        facts: [],
        metrics: [{ key: 'Messages', value: String(messages) }],
        participants: lanes,
        events,
        accuracy: 'MEASURED',
        sources: ['local'],
        clockOrdering: 'SAME_SOURCE',
        clockOrdered: 0,
      },
    ],
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.stdout.write(`${JSON.stringify(largeReport(), null, 2)}\n`)
